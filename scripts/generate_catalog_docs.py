"""Write Docs/data_dictionary.md and Governance/test_catalog.md from dbt's own
metadata (manifest.json + catalog.json), so the docs cannot drift from the code.

Run after `make docs` (dbt docs generate):
    python scripts/generate_catalog_docs.py
"""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "DBT" / "target"
LAYERS = [
    ("seed", "Reference data (seeds)"),
    ("staging", "Silver: staging (cleaned, typed, one row per source record)"),
    ("intermediate", "Silver: intermediate (business rules)"),
    ("core", "Gold: star schema (facts and dimensions)"),
    ("metrics", "Gold: governed KPI marts"),
]


def main() -> None:
    manifest = json.loads((TARGET / "manifest.json").read_text())
    catalog = json.loads((TARGET / "catalog.json").read_text())
    nodes = manifest["nodes"]
    counts = {}
    db = ROOT / "warehouse" / "decisiongrade.duckdb"
    if db.exists():
        import duckdb
        con = duckdb.connect(str(db), read_only=True)
        for schema, name in con.execute(
            "select table_schema, table_name from information_schema.tables"
        ).fetchall():
            counts[(schema, name)] = con.execute(f'select count(*) from "{schema}"."{name}"').fetchall()[0][0]

    # ---- data dictionary
    by_layer = defaultdict(list)
    for uid, n in nodes.items():
        if n["resource_type"] in ("model", "seed"):
            by_layer["seed" if n["resource_type"] == "seed" else n["schema"]].append((uid, n))
    out = ["# Data dictionary", "",
           "Generated from dbt metadata by `scripts/generate_catalog_docs.py`. "
           "Row counts are from the full dataset build.", ""]
    for layer, title in LAYERS:
        out += [f"## {title}", ""]
        for uid, n in sorted(by_layer[layer], key=lambda x: x[1]["name"]):
            cat = catalog["nodes"].get(uid, {})
            rows = counts.get((n["schema"], n["name"]))
            desc = " ".join((n.get("description") or "").split())
            out.append(f"### `{n['schema']}.{n['name']}`")
            if desc:
                out.append(desc)
            if rows is not None:
                out.append(f"\nRows: {int(rows):,}")
            out += ["", "| Column | Type | Description |", "|---|---|---|"]
            for col in cat.get("columns", {}).values():
                cdesc = n["columns"].get(col["name"], {}).get("description", "")
                out.append(f"| `{col['name']}` | {col['type'].lower()} | {cdesc} |")
            out.append("")
    (ROOT / "Docs" / "data_dictionary.md").write_text("\n".join(out))

    # ---- test catalog
    rows = []
    for uid, n in nodes.items():
        if n["resource_type"] != "test":
            continue
        meta = n.get("test_metadata")
        kind = meta["name"] if meta else "custom business rule"
        target = n.get("attached_node") or ", ".join(d.split(".")[-1] for d in n["depends_on"]["nodes"])
        target = target.split(".")[-1]
        col = n.get("column_name") or ""
        sev = n["config"]["severity"].lower()
        rows.append((sev, kind, target, col, n["name"]))
    rows.sort(key=lambda r: (r[0] != "error", r[2], r[1]))
    counts = defaultdict(int)
    for r in rows:
        counts[(r[0], r[1])] += 1
    out = ["# Data quality test catalog", "",
           f"{len(rows)} automated tests run on every `dbt build`. Generated by `scripts/generate_catalog_docs.py`.", "",
           "- **error** severity: a failure stops every downstream model and fails CI, so the pull request cannot merge.",
           "- **warn** severity: reported in the build log and the CI summary, but does not block.", "",
           "## Summary", "", "| Severity | Test type | Count |", "|---|---|---|"]
    out += [f"| {s} | {k} | {c} |" for (s, k), c in sorted(counts.items())]
    out += ["", "## All tests", "", "| Severity | Type | Model | Column | Test |", "|---|---|---|---|---|"]
    out += [f"| {s} | {k} | `{t}` | {('`'+c+'`') if c else ''} | `{nm}` |" for s, k, t, c, nm in rows]
    (ROOT / "Governance" / "test_catalog.md").write_text("\n".join(out) + "\n")
    print("Wrote Docs/data_dictionary.md and Governance/test_catalog.md")


if __name__ == "__main__":
    main()
